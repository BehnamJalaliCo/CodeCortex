UNICODE_LINES = {
    "python": ("app/auth.py", "user"),
    "typescript": ("src/auth.ts", "user"),
}


@pytest.mark.parametrize("fixture", INDEXES, ids=IDS)
def test_real_columns_are_utf16_not_code_points(fixture: RealIndex) -> None:
    """Re-derive the compatibility table's measurement from the committed index.

    A wrong entry in ``compatibility.MEASURED_INDEXERS`` fails here rather than
    silently shifting every column on a non-ASCII line.
    """
    path, needle = UNICODE_LINES[fixture.name]
    imported = fixture.imported()
    source = (fixture.directory / path).read_text(encoding="utf-8").splitlines()
    line_number = next(
        index
        for index, text in enumerate(source)
        if not text.isascii() and needle in text
    )
    line = source[line_number]
    character_column = line.index(needle)
    utf16 = sum(2 if ord(char) > 0xFFFF else 1 for char in line[:character_column])
    utf8 = len(line[:character_column].encode("utf-8"))
    # The three candidate encodings must actually disagree here, or the test
    # would pass for the wrong reason.
    assert len({character_column, utf16, utf8}) == 3

    document = imported.document(path)
    assert document is not None
    emitted = [
        item.range.start_column
        for item in document.occurrences
        if item.range.start_line == line_number
        and item.range.end_column - item.range.start_column == len(needle)
    ]
    assert utf16 in emitted, (line, character_column, utf16, utf8, emitted)
    assert character_column not in emitted

    converted = protocol_to_character(line, utf16, document.position_encoding)
    assert converted.column == character_column


@pytest.mark.parametrize("fixture", INDEXES, ids=IDS)
def test_real_indexes_reuse_local_ids_across_documents(fixture: RealIndex) -> None:
    """The collision this hardening fixes is what real indexers actually emit."""
    imported = fixture.imported()
    per_document = {
        document.relative_path: {
            item.symbol
            for item in document.occurrences
            if item.symbol.startswith("local ")
        }
        for document in imported.documents
    }
    populated = [names for names in per_document.values() if names]
    assert len(populated) >= 2
    shared = set.intersection(*populated)
    assert shared, per_document

    # Each shared id must resolve only within the document that declares it.
    for local in sorted(shared):
        owners = [path for path, names in per_document.items() if local in names]
        assert len(owners) >= 2
        for owner in owners:
            paths = {item.path for item in imported.occurrences_for(local, owner)}
            assert paths == {owner}
        assert imported.occurrences_for(local) == ()


def test_python_duplicate_function_names_resolve_by_identity(tmp_path: Path) -> None:
    """Two modules export session_token; only the symbol identity separates them."""
    provider = _provider(PYTHON, tmp_path)
    index = PYTHON.imported()
    definitions = {
        item.symbol: item.path
        for document in index.documents
        for item in document.occurrences
        if item.is_definition and item.symbol.endswith("session_token().")
    }
    assert len(definitions) == 2
    assert set(definitions.values()) == {"app/auth.py", "app/billing.py"}

    for symbol, path in definitions.items():
        bundle = provider.evidence_for_symbol(symbol, EvidenceKind.DEFINITION)
        assert [record.path for record in bundle.records] == [path]
        assert all(record.trust is TrustTier.EXACT for record in bundle.records)


def test_typescript_interface_implementations_are_reported(tmp_path: Path) -> None:
    """Implementation direction comes from the relationship, not from names."""
    index = TYPESCRIPT.imported()
    edges = {
        (item.symbol, relationship.symbol)
        for document in index.documents
        for item in document.symbols
        for relationship in item.relationships
        if relationship.is_implementation
    }
    assert edges, "the TypeScript fixture must carry implementation edges"

    provider = _provider(TYPESCRIPT, tmp_path)
    by_interface: dict[str, set[str]] = {}
    for implementer, interface in edges:
        by_interface.setdefault(interface, set()).add(implementer)

    for interface, implementers in sorted(by_interface.items()):
        bundle = provider.evidence_for_symbol(interface, EvidenceKind.IMPLEMENTATION)
        returned = {record.target_symbol for record in bundle.records}
        # Every implementer is returned, and the interface itself never is.
        assert returned == implementers
        assert all(record.exact for record in bundle.records)
        # The reverse direction must be empty: an implementer has no
        # implementers here, and inferring one from the shared name would be
        # exactly the name-based guess the relationship exists to replace.
        for implementer in sorted(implementers):
            reverse = provider.evidence_for_symbol(
                implementer, EvidenceKind.IMPLEMENTATION
            )
            assert reverse.records == []


@pytest.mark.parametrize("fixture", INDEXES, ids=IDS)
def test_caret_navigation_on_a_unicode_line(fixture: RealIndex, tmp_path: Path) -> None:
    """The end-to-end case: a caret on a line whose columns are UTF-16."""
    path, needle = UNICODE_LINES[fixture.name]
    provider = _provider(fixture, tmp_path)
    source = (fixture.directory / path).read_text(encoding="utf-8").splitlines()
    line_number = next(
        index for index, text in enumerate(source) if not text.isascii() and needle in text
    )
    character_column = source[line_number].index(needle)

    bundle = provider.definition(
        PrecisionQuery(path, line_number + 1, character_column + 1)
    )
    assert bundle.records, (path, line_number, character_column)
    record = bundle.records[0]
    assert record.exact
    assert record.trust is TrustTier.EXACT
    assert needle in str(record.metadata["symbol_identity"]["symbol"])

    # One column to the left is inside the Unicode text and must not resolve to
    # the identifier: that is exactly the off-by-N a missing conversion causes.
    before = provider.definition(PrecisionQuery(path, line_number + 1, 1))
    assert [item.target_symbol for item in before.records] != [record.target_symbol]


KNOWN_ROLE_BITS = int(
    SymbolRole.DEFINITION
    | SymbolRole.IMPORT
    | SymbolRole.WRITE_ACCESS
    | SymbolRole.READ_ACCESS
    | SymbolRole.GENERATED
    | SymbolRole.TEST
    | SymbolRole.FORWARD_DEFINITION
)


@pytest.mark.parametrize("fixture", INDEXES, ids=IDS)
def test_role_flags_decode_to_named_roles(fixture: RealIndex) -> None:
    seen: set[str] = set()
    for document in fixture.imported().documents:
        for occurrence in document.occurrences:
            seen.update(occurrence.role_names())
            # Every emitted bit must be a role the schema defines.
            assert occurrence.roles == occurrence.roles & KNOWN_ROLE_BITS
    assert "definition" in seen


@pytest.mark.parametrize("fixture", INDEXES, ids=IDS)
def test_a_reference_is_recognised_whether_or_not_a_read_bit_is_set(
    fixture: RealIndex,
) -> None:
    """The two pinned indexers disagree about role bits on references.

    scip-python marks a reference ``ReadAccess``; scip-typescript emits ``0``.
    Both are references, so reference lookup must key off the absence of the
    Definition bit rather than the presence of a read bit.
    """
    imported = fixture.imported()
    references = [
        occurrence
        for document in imported.documents
        for occurrence in document.occurrences
        if not occurrence.is_definition
    ]
    assert references
    for occurrence in references:
        scope = occurrence.path if occurrence.symbol.startswith("local ") else None
        assert occurrence in imported.references_for(occurrence.symbol, scope)


def test_the_two_real_indexers_use_different_reference_role_bits() -> None:
    """Pin the observed difference, so a fixture refresh that changes it is visible."""

    def reference_roles(fixture: RealIndex) -> set[int]:
        return {
            occurrence.roles
            for document in fixture.imported().documents
            for occurrence in document.occurrences
            if not occurrence.is_definition
        }

    assert int(SymbolRole.READ_ACCESS) in reference_roles(PYTHON)
    assert reference_roles(TYPESCRIPT) == {0}


# -- helpers ----------------------------------------------------------------


def _provider(fixture: RealIndex, tmp_path: Path) -> PrecisionEvidenceProvider:
    """Serve the fixture from a temporary root whose sources look freshly indexed."""
    import os
    import shutil
    import time

    root = tmp_path / fixture.name
    shutil.copytree(fixture.directory, root)
    later = time.time() + 600
    os.utime(root / "index.scip", (later, later))
    return PrecisionEvidenceProvider(root, CortexConfig(project_root=root))
