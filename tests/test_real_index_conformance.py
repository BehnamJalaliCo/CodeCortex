@pytest.mark.parametrize("fixture", INDEXES, ids=IDS)
def test_relationships_agree_with_the_official_decode(fixture: RealIndex) -> None:
    imported = fixture.imported()
    official_edges: set[tuple[str, str]] = set()
    documents = fixture.official["documents"]
    assert isinstance(documents, list)
    for official_document in documents:
        for item in official_document.get("symbols") or []:
            for relationship in item.get("relationships") or []:
                if relationship.get("is_implementation"):
                    official_edges.add((item["symbol"], relationship["symbol"]))
    ours = {
        (item.symbol, relationship.symbol)
        for document in imported.documents
        for item in document.symbols
        for relationship in item.relationships
        if relationship.is_implementation
    }
    assert ours == official_edges


