"""Validate CodeCortex against indexes produced by real language indexers.

The fixtures under ``tests/fixtures/real_index`` were generated by pinned
upstream indexers and validated with the official CLI (``scip lint`` clean,
``scip print --json`` committed as ``expected.json``). Each project's
``PROVENANCE.json`` records the exact generator commit, command, and digests;
``scripts/regenerate_real_index_fixtures.sh`` reproduces them.

The tests compare CodeCortex's own decode against the official decode, and then
assert the navigation behaviour those indexes actually require. Synthetic
fixtures cannot do this job: every interesting property here — undeclared
position encodings, UTF-16 columns from a Python indexer, ``local`` ids reused
across documents, the compact range encoding — is a real indexer's behaviour
that a hand-built fixture would have had to guess.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from pathlib import Path

import pytest

from codecortex.config import CortexConfig
from codecortex.evidence.models import EvidenceKind, TrustTier
from codecortex.precision.compatibility import EncodingSource
from codecortex.precision.importer import import_index
from codecortex.precision.models import PrecisionIndex, PrecisionOccurrence
from codecortex.precision.positions import protocol_to_character
from codecortex.precision.provider import PrecisionEvidenceProvider, PrecisionQuery
from codecortex.precision.schema import PositionEncoding, SymbolRole

FIXTURE_ROOT = Path(__file__).resolve().parent / "fixtures" / "real_index"


@dataclass(frozen=True, slots=True)
class RealIndex:
    """One committed real index, with its oracle output and provenance."""

    name: str
    directory: Path

    @property
    def manifest(self) -> dict[str, object]:
        payload: dict[str, object] = json.loads(
            (self.directory / "PROVENANCE.json").read_text(encoding="utf-8")
        )
        return payload

    @property
    def payload(self) -> bytes:
        return (self.directory / "index.scip").read_bytes()

    @property
    def official(self) -> dict[str, object]:
        """The official CLI's decode of the same bytes."""
        decoded: dict[str, object] = json.loads(
            (self.directory / "expected.json").read_text(encoding="utf-8")
        )
        return decoded

    def imported(self) -> PrecisionIndex:
        return import_index(self.payload)


PYTHON = RealIndex("python", FIXTURE_ROOT / "python_project")
TYPESCRIPT = RealIndex("typescript", FIXTURE_ROOT / "typescript_project")
INDEXES = (PYTHON, TYPESCRIPT)
IDS = [item.name for item in INDEXES]


# -- provenance -------------------------------------------------------------


@pytest.mark.parametrize("fixture", INDEXES, ids=IDS)
def test_committed_index_matches_its_provenance_manifest(fixture: RealIndex) -> None:
    """A fixture edited by hand rather than regenerated must fail here."""
    manifest = fixture.manifest
    assert hashlib.sha256(fixture.payload).hexdigest() == manifest["index_hash"]
    expected_bytes = (fixture.directory / "expected.json").read_bytes()
    assert hashlib.sha256(expected_bytes).hexdigest() == manifest["expected_json_hash"]
    assert manifest["oracle"] == {
        "tool": "scip",
        "repository": "https://github.com/scip-code/scip",
        "commit": "1c2b6db7e560d5233c944f36e4ac1377cc6963fc",
        "lint": "clean",
        "expected_json_command": "scip print --json index.scip",
    }


@pytest.mark.parametrize("fixture", INDEXES, ids=IDS)
def test_the_recorded_generator_produced_the_committed_index(fixture: RealIndex) -> None:
    manifest = fixture.manifest
    tool = fixture.imported()
    assert tool.tool_name == manifest["generator_tool"]
    assert tool.tool_version == manifest["generator_version"]


# -- CodeCortex decode versus the official decode ---------------------------


def _official_range(occurrence: dict[str, object]) -> tuple[int, int, int, int]:
    """Normalise the official CLI's range shapes into (sl, sc, el, ec)."""
    compact = occurrence.get("range")
    if isinstance(compact, list) and len(compact) == 3:
        return compact[0], compact[1], compact[0], compact[2]
    if isinstance(compact, list) and len(compact) == 4:
        return compact[0], compact[1], compact[2], compact[3]
    typed = occurrence.get("TypedRange") or {}
    assert isinstance(typed, dict)
    single = typed.get("single_line_range")
    if isinstance(single, dict):
        line = single.get("line", 0)
        return line, single.get("start_character", 0), line, single.get("end_character", 0)
    multi = typed.get("multi_line_range")
    assert isinstance(multi, dict), occurrence
    return (
        multi.get("start_line", 0),
        multi.get("start_character", 0),
        multi.get("end_line", 0),
        multi.get("end_character", 0),
    )


def _codecortex_range(occurrence: PrecisionOccurrence) -> tuple[int, int, int, int]:
    span = occurrence.range
    return span.start_line, span.start_column, span.end_line, span.end_column


@pytest.mark.parametrize("fixture", INDEXES, ids=IDS)
def test_document_set_agrees_with_the_official_decode(fixture: RealIndex) -> None:
    official = [
        document["relative_path"]
        for document in fixture.official["documents"]  # type: ignore[index,union-attr]
    ]
    assert list(fixture.imported().paths()) == official


@pytest.mark.parametrize("fixture", INDEXES, ids=IDS)
def test_every_occurrence_agrees_with_the_official_decode(fixture: RealIndex) -> None:
    """Symbol, range, and roles must match the reference implementation exactly."""
    imported = fixture.imported()
    documents = fixture.official["documents"]
    assert isinstance(documents, list)
    for official_document in documents:
        path = official_document["relative_path"]
        document = imported.document(path)
        assert document is not None, path
        official_occurrences = [
            (item["symbol"], _official_range(item), item.get("symbol_roles", 0))
            for item in official_document["occurrences"]
        ]
        ours = [
            (item.symbol, _codecortex_range(item), item.roles)
            for item in document.occurrences
        ]
        assert ours == official_occurrences, path


